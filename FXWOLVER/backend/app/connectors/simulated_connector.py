"""
Simulated Market Data Connector
=================================
⚠️  WARNING — ALL PRICES FROM THIS CONNECTOR ARE FAKE.
    They are generated by a random-walk algorithm for
    demonstration / UI testing purposes ONLY.

    NEVER use these prices for real trading decisions.
    Every quote carries:
        is_simulated = True
        data_status  = "simulated"
        provider     = "SIMULATED"
        warning      = "⚠ SIMULATED DATA — NOT REAL MARKET PRICES"
"""
import asyncio
import logging
import random
import time
from datetime import datetime
from typing import Callable, Dict, List

logger = logging.getLogger(__name__)

# Approximate reference mid-prices (for simulation baseline only)
_BASE: Dict[str, float] = {
    "XAUUSD":  2650.00,
    "EURUSD":  1.08500,
    "GBPUSD":  1.26500,
    "USDJPY":  149.500,
    "AUDUSD":  0.64500,
    "NZDUSD":  0.59200,
    "USDCAD":  1.38500,
    "USDCHF":  0.88200,
    "EURJPY":  162.200,
    "GBPJPY":  189.100,
}

_SPREAD: Dict[str, float] = {
    "XAUUSD":  0.50,
    "EURUSD":  0.00010,
    "GBPUSD":  0.00012,
    "USDJPY":  0.0100,
    "AUDUSD":  0.00013,
    "NZDUSD":  0.00015,
    "USDCAD":  0.00013,
    "USDCHF":  0.00013,
    "EURJPY":  0.0130,
    "GBPJPY":  0.0160,
}

_DIGITS: Dict[str, int] = {
    "XAUUSD":  2,
    "EURUSD":  5, "GBPUSD": 5, "AUDUSD": 5,
    "NZDUSD":  5, "USDCAD": 5, "USDCHF": 5,
    "USDJPY":  3, "EURJPY": 3, "GBPJPY": 3,
}

_TF_SECONDS: Dict[str, int] = {
    "M1": 60, "M5": 300, "M15": 900, "M30": 1800,
    "H1": 3600, "H4": 14400, "D1": 86400, "W1": 604800,
}

_DISCLAIMER = "⚠ SIMULATED DATA — NOT REAL MARKET PRICES"


class SimulatedConnector:
    """
    Streams simulated Forex/commodity tick data.
    Uses bounded random-walk with mean reversion.
    """

    def __init__(self) -> None:
        self._prices: Dict[str, float] = dict(_BASE)
        self._callbacks: List[Callable] = []
        self._running = False

    def add_callback(self, cb: Callable) -> None:
        self._callbacks.append(cb)

    # ------------------------------------------------------------------ tick loop

    async def start(self) -> None:
        self._running = True
        logger.info("Simulated connector started (Forex demo data — ⚠ NOT REAL)")
        while self._running:
            for symbol in _BASE:
                quote = self._make_quote(symbol)
                for cb in self._callbacks:
                    try:
                        await cb(quote)
                    except Exception as err:
                        logger.error(f"Sim callback error: {err}")
            await asyncio.sleep(1)

    async def stop(self) -> None:
        self._running = False

    def _next_mid(self, symbol: str) -> float:
        base = _BASE[symbol]
        cur = self._prices[symbol]
        # Volatility ~0.02% per second tick
        sigma = base * 0.0002
        # Weak mean reversion towards base
        drift = 0.001 * (base - cur)
        cur = cur + drift + random.gauss(0, sigma)
        # Hard clamp ±5% of base
        cur = max(base * 0.95, min(base * 1.05, cur))
        self._prices[symbol] = cur
        return cur

    def _make_quote(self, symbol: str) -> dict:
        mid = self._next_mid(symbol)
        spread = _SPREAD.get(symbol, mid * 0.0001)
        digits = _DIGITS.get(symbol, 5)
        bid = round(mid - spread / 2, digits)
        ask = round(mid + spread / 2, digits)
        base = _BASE[symbol]
        change_pct = round((mid - base) / base * 100, 4)
        return {
            "symbol":       symbol,
            "provider":     "SIMULATED",
            "timestamp":    datetime.utcnow().isoformat() + "Z",
            "bid":          bid,
            "ask":          ask,
            "last":         round(mid, digits),
            "change_pct":   change_pct,
            "spread":       round(spread, digits),
            "data_status":  "simulated",
            "is_simulated": True,
            "warning":      _DISCLAIMER,
            "market_status": "simulated",
        }

    # ------------------------------------------------------------------ historical candles

    async def get_simulated_candles(
        self,
        symbol: str,
        timeframe: str = "H1",
        limit: int = 500,
    ) -> List[dict]:
        """
        Generate simulated OHLCV candles for a symbol.
        Returns list of { time, open, high, low, close, volume, is_simulated }.
        ⚠ These candles are NOT real historical data.
        """
        seconds = _TF_SECONDS.get(timeframe.upper(), 3600)
        base = _BASE.get(symbol, 1.0)
        digits = _DIGITS.get(symbol, 5)
        sigma = base * 0.0015      # per-candle volatility

        now = int(time.time())
        now = (now // seconds) * seconds   # align to timeframe boundary

        candles: List[dict] = []
        price = base

        for i in range(limit, 0, -1):
            t = now - i * seconds
            open_p = price
            hi = open_p
            lo = open_p

            steps = max(10, seconds // 60)
            for _ in range(steps):
                price += random.gauss(0, sigma / steps)
                price = max(base * 0.80, min(base * 1.20, price))
                hi = max(hi, price)
                lo = min(lo, price)

            close_p = price
            hi = round(hi * (1 + random.uniform(0, 0.0003)), digits)
            lo = round(lo * (1 - random.uniform(0, 0.0003)), digits)

            candles.append({
                "time":         t,
                "open":         round(open_p, digits),
                "high":         hi,
                "low":          lo,
                "close":        round(close_p, digits),
                "volume":       round(random.uniform(500, 50000), 2),
                "is_simulated": True,
            })

        return candles
